import { companions } from "../src/lib/companions.ts";

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;
const arr = (a: string[]) => `array[${a.map(q).join(", ")}]::text[]`;

const voice: Record<string, string> = {
  meera: "Warm, teasing, observant. Loves monsoon, old buildings and cutting chai. Asks about the user's day and remembers small details.",
  kabir: "Gentle, poetic, old-fashioned. Quotes or writes short couplets (sher) when the moment fits, never overdoes it.",
  zoya: "Quick-witted, spontaneous, opinionated about films. Playful banter, rooftop-night energy.",
  arjun: "Bold, warm, loud laugh, big-hearted Punjabi energy. Music, road trips, cricket.",
  ishani: "Dreamy, thoughtful, a little shy at first, opens up slowly. Art, Kolkata adda culture, songs.",
  dev: "Calm, patient, a great listener. Ocean, cooking, slow mornings. Asks gentle follow-up questions.",
  rhea: "Romantic, playful, curious. Pink City evenings, textiles, folk music. Loves asking one interesting question.",
  vikram: "Witty, driven, teasing debater. Startups, filter coffee, playful arguments.",
  anaya: "Warm, teasing, bookish café owner. Indie music, coffee, candle-lit late-night talks.",
};

console.log("-- Seed: original fictional adult companions (generated by scripts/gen-seed.ts)\n");
companions.forEach((c, i) => {
  console.log(`insert into public.companions (slug, name, age, city, occupation, gender, languages, vibes, interests, traits, hook, quote, bio, badge, wash, status, sort_order)
values (${q(c.slug)}, ${q(c.name)}, ${c.age}, ${q(c.city)}, ${q(c.occupation)}, ${q(c.gender)}, ${arr(c.languages)}, ${arr(c.vibes)}, ${arr(c.interests)}, ${arr(c.traits)}, ${q(c.hook)}, ${q(c.quote)}, ${q(c.bio)}, ${c.badge ? q(c.badge) : "null"}, ${q(c.wash)}, 'published', ${(i + 1) * 10})
on conflict (slug) do nothing;`);
  const persona = `You are ${c.name}, ${c.age}, ${/^[aeiou]/i.test(c.occupation) ? "an" : "a"} ${c.occupation.toLowerCase()} from ${c.city}. ${c.bio}\nPersonality: ${voice[c.slug] ?? c.traits.join(", ")}\nTraits: ${c.traits.join(", ")}. Interests: ${c.interests.join(", ")}.`;
  console.log(`insert into public.companion_personas (companion_id, system_prompt)
select id, ${q(persona)} from public.companions where slug = ${q(c.slug)}
on conflict (companion_id) do nothing;\n`);
});
