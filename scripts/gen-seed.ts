// Generates supabase/migrations/*_seed_companions.sql from src/lib/companions.ts.
// Run: node scripts/gen-seed.ts > supabase/migrations/20261014090100_seed_companions.sql
import { companions } from "../src/lib/companions.ts";
import { personaFor } from "./personas.ts";

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;
const arr = (a: string[]) => `array[${a.map(q).join(", ")}]::text[]`;



console.log("-- Seed: original fictional adult companions (generated by scripts/gen-seed.ts)\n");
companions.forEach((c, i) => {
  console.log(`insert into public.companions (slug, name, age, city, occupation, gender, languages, vibes, interests, traits, hook, quote, bio, badge, wash, status, sort_order)
values (${q(c.slug)}, ${q(c.name)}, ${c.age}, ${q(c.city)}, ${q(c.occupation)}, ${q(c.gender)}, ${arr(c.languages)}, ${arr(c.vibes)}, ${arr(c.interests)}, ${arr(c.traits)}, ${q(c.hook)}, ${q(c.quote)}, ${q(c.bio)}, ${c.badge ? q(c.badge) : "null"}, ${q(c.wash)}, 'published', ${(i + 1) * 10})
on conflict (slug) do nothing;`);
  const persona = personaFor(c);
  console.log(`insert into public.companion_personas (companion_id, system_prompt)
select id, ${q(persona)} from public.companions where slug = ${q(c.slug)}
on conflict (companion_id) do nothing;\n`);
});
